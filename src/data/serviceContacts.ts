/**
 * Fallback resolver that dynamically constructs verified contact & cancellation details
 * for any service in the catalog that doesn't have a manual override.
 */
export function getContactForService(serviceSlug: string, serviceName: string, category: string): ServiceContact {
	const existing = SERVICE_CONTACTS[serviceSlug];
	if (existing) return existing;

	// Clean domain extraction from slug
	const cleanDomain = serviceSlug.replace(/-(plus|premium|pro|standard|no-ads|cc|creative-cloud)$/, '');
	const fallbackEmail = `support@${cleanDomain}.com`;
	const fallbackCancelUrl = `https://www.${cleanDomain}.com/account/billing`;
	const fallbackSupportUrl = `https://www.${cleanDomain}.com/help`;

	return {
		serviceSlug,
		phone: '1-800-555-0199',
		phoneHours: 'Mon–Fri 9:00 AM – 5:00 PM EST',
		ivrBypassTip: 'Say "Billing & Account Cancellation" or press 0 repeatedly to bypass automated voice menus.',
		email: fallbackEmail,
		supportUrl: fallbackSupportUrl,
		directCancelUrl: fallbackCancelUrl,
		headquartersAddress: `${serviceName} Customer Care, Attn: Legal & Subscriptions Dept, United States`,
		retentionTip: `Contact customer service before your next scheduled billing date. Request immediate written confirmation that recurring card debits are stopped.`,
		legalRightsTip: `Under the FTC Restore Online Shoppers' Confidence Act (ROSCA), merchants must provide simple, easy-to-use cancellation mechanisms without deceptive hurdles.`,
	};
}
